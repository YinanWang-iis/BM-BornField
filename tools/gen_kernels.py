#!/usr/bin/env python
"""Generate lammps/egcnn_generated.hpp (straight-line SH + 17-path 'uvu' tensor product) from an exported JSON.
The coefficients depend only on the architecture (64x0e+64x1o+64x1e+64x2e, SH lmax 2), identical for both models.
    python gen_kernels.py models/egcnn_bto.json lammps/egcnn_generated.hpp"""
import json, sys
d = json.load(open(sys.argv[1]))
xo = {0: 0, 1: 1, 2: 4, 3: 7}          # node block -> offset in the per-channel 12-vector (0e,1o,1e,2e)
yo = {0: 0, 1: 1, 2: 4}                # sh block -> offset in Y[9]
L = []
L.append("// generated by tools/gen_kernels.py from " + d["source"] + " -- do not edit")
L.append("#pragma once")
L.append("namespace egcnn {")
L.append(f"constexpr int NPATH = {len(d['tp'])};")
# SH
mons = d["sh"]["monomials"]
L.append("template <class T> __device__ __forceinline__ void sh(T x, T y, T z, T* Y) {")
for k, row in enumerate(d["sh"]["coef"]):
    terms = []
    for c, m in zip(row, mons):
        if c == 0: continue
        f = "*".join(["x"] * m[0] + ["y"] * m[1] + ["z"] * m[2]) or "T(1)"
        terms.append(f"T({c!r})*{f}")
    L.append(f"  Y[{k}] = {' + '.join(terms) if terms else 'T(0)'};")
L.append("}")
# TP
L.append("template <class T> __device__ __forceinline__ void tp(const T* xa, const T* Y, const T* w, T* acc) {")
flat = []
for p, P in enumerate(d["tp"]):
    C = P["C"]
    for c in range(2 * P["l3"] + 1):
        terms = []
        for a in range(2 * P["l1"] + 1):
            for b in range(2 * P["l2"] + 1):
                v = C[a][b][c]
                if abs(v) > 1e-14:
                    terms.append(f"T({v!r})*xa[{xo[P['i1']] + a}]*Y[{yo[P['i2']] + b}]")
        if terms:
            L.append(f"  acc[{xo[P['io']] + c}] += w[{p}]*({' + '.join(terms)});")
L.append("}")
for P in d["tp"]:
    flat += [v for A in P["C"] for B in A for v in B]           # same a,b,c order as the JSON nesting
L.append(f"constexpr int NCOEF = {len(flat)};")
L.append("inline const double* coef_check() { static const double c[] = {" + ", ".join(repr(v) for v in flat) + "}; return c; }")
L.append("inline const int* path_check() { static const int c[] = {" + ", ".join(
    str(v) for P in d["tp"] for v in (P["i1"], P["i2"], P["io"])) + "}; return c; }")
L.append("}  // namespace egcnn")
open(sys.argv[2], "w").write("\n".join(L) + "\n")
print("written", sys.argv[2])
